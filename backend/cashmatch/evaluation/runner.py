"""Running the whole pipeline and scoring it against the answer key.

This is the only module in the project that opens the ground-truth file, and
it opens it **after** matching and scoring have finished. That ordering is
the integrity of every number in the report: the matcher cannot have seen
the answers, because the answers are not loaded until it has stopped running.

The separation is physical too. Ground truth lives in
``data/ground_truth/ground_truth.json``, never in the database the matcher
queries, and a schema test asserts no scenario or truth column exists on
``bank_transactions``.
"""

from __future__ import annotations

from pathlib import Path

from sqlalchemy.orm import Session

from cashmatch.evaluation.comparison import Comparison, compare
from cashmatch.evaluation.metrics import EvaluationReport, build_report
from cashmatch.evaluation.sweep import SweepRow, sweep_thresholds
from cashmatch.generator.engine import load_ground_truth
from cashmatch.matching.config import MatchingConfig
from cashmatch.matching.runner import run_matching
from cashmatch.scoring.runner import score_outcomes
from cashmatch.scoring.scorer import Scored


class GroundTruthMissingError(RuntimeError):
    """The answer key is not where it should be."""


def evaluate(
    session: Session,
    config: MatchingConfig,
    output_root: Path,
    *,
    use_advice: bool = True,
    thresholds: list[float] | None = None,
) -> tuple[EvaluationReport, list[SweepRow], list[Comparison]]:
    """Match, score, then compare against the answer key.

    Nothing is written to the database. Evaluation reads the same inputs the
    engine reads, runs it, and judges the output -- it never adjusts
    anything, which is what keeps the measurement honest.
    """
    # 1. Run the engine. No ground truth is in scope yet, by construction.
    outcomes, _ = run_matching(session, config, use_advice=use_advice)
    scored: list[Scored] = score_outcomes(outcomes, config)

    # 2. Only now open the answers.
    try:
        truth = load_ground_truth(output_root)
    except FileNotFoundError as exc:
        raise GroundTruthMissingError(
            f"No answer key found under {output_root}. Evaluation compares the engine's "
            "output against the ground truth written by `cashmatch generate`, so the "
            "dataset has to have been generated by this project rather than loaded "
            "from elsewhere."
        ) from exc

    by_ref = truth.by_statement_ref()
    tolerance = config.amount.tolerance_paise

    comparisons = [
        compare(item, by_ref[item.outcome.statement_ref], tolerance)
        for item in scored
        if item.outcome.statement_ref in by_ref
    ]

    missing = len(scored) - len(comparisons)
    if missing:
        raise GroundTruthMissingError(
            f"{missing} of {len(scored)} transactions have no entry in the answer key. "
            "The database and the ground-truth file are out of step -- re-run "
            "`cashmatch generate --reset` so both come from the same seed."
        )

    report = build_report(comparisons)
    report.config_digest = truth.config_digest
    report.seed = truth.seed
    report.thresholds = (
        config.scoring.thresholds.auto_apply,
        config.scoring.thresholds.review_floor,
    )

    rows = sweep_thresholds(
        scored, by_ref, config.scoring, thresholds=thresholds, tolerance_paise=tolerance
    )

    return report, rows, comparisons


def signal_ablation(
    session: Session,
    config: MatchingConfig,
    output_root: Path,
) -> dict[str, EvaluationReport]:
    """Measure what each signal is worth by removing it.

    Zero a signal's weight, redistribute it proportionally across the rest,
    re-score, re-judge. The drop in precision or auto-match rate is that
    signal's contribution -- measured rather than asserted, which is the
    only way to defend a weighting in a room.
    """
    from cashmatch.evaluation.sweep import rescore

    outcomes, _ = run_matching(session, config, use_advice=True)
    truth = load_ground_truth(output_root).by_statement_ref()
    tolerance = config.amount.tolerance_paise

    results: dict[str, EvaluationReport] = {}
    names = list(config.scoring.weights.as_dict())

    for name in names:
        weights = config.scoring.weights.as_dict()
        removed = weights[name]
        if removed >= 1.0:
            continue
        weights[name] = 0.0
        # Redistribute proportionally so the remaining weights still sum to
        # one and the confidences stay comparable.
        scale = 1.0 / (1.0 - removed)
        weights = {key: value * scale for key, value in weights.items()}

        variant = config.scoring.model_copy(deep=True)
        variant.weights = type(config.scoring.weights)(**weights)

        scored = rescore(outcomes, variant)
        comparisons = [
            compare(item, truth[item.outcome.statement_ref], tolerance)
            for item in scored
            if item.outcome.statement_ref in truth
        ]
        results[name] = build_report(comparisons)

    return results
